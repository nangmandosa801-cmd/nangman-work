# GTX 글 숫자 · m.pkl(매매 2021~2026.10 · 해제 뺌 · 직거래 뺌) r.pkl(전세 2024~2026.10) · 전용 83~86
import pandas as pd, json
m=pd.read_pickle('m.pkl'); x=m[m.a.between(83,86)]; r=pd.read_pickle('r.pkl')
G={'동탄':{'역세권':['더샵센트럴시티','동탄역 시범한화 꿈에그린 프레스티지','동탄역 시범우남퍼스트빌아파트'],'먼곳':['동탄역 호반 써밋','동탄역대원칸타빌포레지움','동탄역모아미래도'],
          'P':{'2021':(202101,202112),'2023':(202301,202312),'전1년':(202304,202403),'후1년':(202404,202503),'2026':(202601,202610)}},
   '운정':{'역세권':['한울마을1단지운정신도시IPARK','운정신도시 센트럴 푸르지오'],'먼곳':['한빛마을9단지롯데캐슬1차','한빛마을4단지롯데캐슬Ⅱ','산내마을7단지화성파크드림'],
          'P':{'2021':(202101,202112),'2023':(202301,202312),'전1년':(202401,202412),'후1년':(202501,202512),'2026':(202601,202610)}},
   '별내':{'역세권':['포레나별내','신안인스빌'],'먼곳':['별내푸르지오','별내아이파크2차','남양주별내리슈빌'],
          'P':{'2021':(202101,202112),'2023':(202301,202312),'2024':(202401,202412),'2025':(202501,202512),'2026':(202601,202610)}}}
PR={'2024':(202401,202412),'2025':(202501,202512),'2026':(202601,202610)}
def med(d,a,b):
    s=d[(d.ym>=a)&(d.ym<=b)].p; return (int(s.median()) if len(s) else None, len(s))
out={}
for city,g in G.items():
    out[city]={}
    for grp in ['역세권','먼곳']:
        for nm in g[grp]:
            d=x[x['단지명']==nm]; e=r[r['단지명']==nm]
            row={'그룹':grp,'준공':int(d.by.iloc[0]),'매매':{k:med(d,a,b) for k,(a,b) in g['P'].items()},'전세':{k:med(e,a,b) for k,(a,b) in PR.items()}}
            out[city][nm]=row
        # 그룹 합산
        d=x[x['단지명'].isin(g[grp])]; e=r[r['단지명'].isin(g[grp])]
        out[city]['['+grp+' 합산]']={'그룹':grp,'매매':{k:med(d,a,b) for k,(a,b) in g['P'].items()},'전세':{k:med(e,a,b) for k,(a,b) in PR.items()}}
json.dump(out,open('an.json','w'),ensure_ascii=False,indent=1)
for city,v in out.items():
    print('=====',city)
    for nm,row in v.items():
        mm=' '.join(f"{k}:{(p or 0)/10000:.2f}({n})" for k,(p,n) in row['매매'].items())
        rr=' '.join(f"{k}:{(p or 0)/10000:.2f}({n})" for k,(p,n) in row['전세'].items())
        print(f"{nm:28s} {row.get('준공','')}  매매 {mm} | 전세 {rr}")
